import { describe, expect, it } from 'vitest';
import {
  meaningfulCaseName,
  resolveValidationSteps,
  squashCaseDescription,
  toSquashUpsertInput,
} from '../src/case-template';

describe('case template', () => {
  it('prefixes names with kind when missing', () => {
    expect(meaningfulCaseName('Saved card is listed', 'positive')).toBe('Positive: Saved card is listed');
    expect(meaningfulCaseName('Negative: bad login', 'negative')).toBe('Negative: bad login');
  });

  it('prefers explicit validation steps over Playwright source', () => {
    const steps = resolveValidationSteps({
      name: 'Positive: pay',
      expected: 'Paid',
      steps: "import { test } from '@playwright/test';\n",
      validationSteps: [{ action: 'Open checkout', expected: 'Form visible' }, { action: 'Pay', expected: 'Paid' }],
    });
    expect(steps).toEqual([
      { action: 'Open checkout', expected: 'Form visible' },
      { action: 'Pay', expected: 'Paid' },
    ]);
  });

  it('derives steps from a // Steps: comment when validationSteps are absent', () => {
    const steps = resolveValidationSteps({
      name: 'Positive: pay',
      expected: 'Receipt shown',
      steps: [
        "import { test, expect } from '@playwright/test';",
        "test('x', async ({ page }) => {",
        '  // Steps: Open PayNSure. Enter card. Confirm payment.',
        "  await expect(page.locator('body')).toBeVisible();",
        '});',
      ].join('\n'),
    });
    expect(steps).toHaveLength(3);
    expect(steps[0]?.action).toMatch(/Open PayNSure/);
    expect(steps[2]?.expected).toBe('Receipt shown');
  });

  it('builds a Squash upsert payload with description and action steps', () => {
    const upsert = toSquashUpsertInput({
      name: 'Saved card is listed',
      kind: 'positive',
      priority: 'medium',
      steps: "import { test } from '@playwright/test';\n",
      expected: 'The card is listed',
      validationSteps: [{ action: 'Open checkout', expected: 'The card is listed' }],
      workItem: '7259',
      reference: 'QAP-7259-1',
      file: 'tests/paynsure/7259.spec.js',
    });
    expect(upsert.name).toBe('Positive: Saved card is listed');
    expect(upsert.reference).toBe('QAP-7259-1');
    expect(upsert.steps).toEqual([{ action: 'Open checkout', expected: 'The card is listed' }]);
    expect(upsert.description).toContain('Kind: positive');
    expect(upsert.description).toContain('Work item: 7259');
    expect(upsert.description).toContain('tests/paynsure/7259.spec.js');
    expect(squashCaseDescription({
      kind: 'edge',
      priority: 'low',
      expected: 'Boundary holds',
    })).toContain('Generated by playwright-test-generator');
  });
});

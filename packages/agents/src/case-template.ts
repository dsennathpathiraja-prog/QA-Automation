/**
 * Per-case template used by planner → generator/healer → platform Test Cases → Squash.
 *
 * Answer for operators: there was no standalone documented template before this module;
 * Zod schemas (`GeneratedCaseSchema`) and `GeneratedPlaywrightCase` carried the shape
 * implicitly. This file is the explicit contract.
 */

export type CaseKind = 'positive' | 'negative' | 'edge';
export type CasePriority = 'high' | 'medium' | 'low';

/** One Squash action-step (maps to POST …/steps action + expected_result). */
export interface ValidationStep {
  action: string;
  expected: string;
}

/**
 * Canonical fields every generated case must carry through the pipeline.
 * Platform library stores Playwright source in `steps`; Squash gets `validationSteps`.
 */
export interface CaseTemplateFields {
  /** Human title; prefer `Kind: short goal` (e.g. `Positive: Saved card is listed`). */
  name: string;
  kind: CaseKind;
  priority: CasePriority;
  /** Playwright `.spec.js` source for the platform Test Cases library / runner. */
  steps: string;
  /** Overall expected outcome (also used on the last validation step when needed). */
  expected: string;
  /** Human validation steps published to Squash (action + expected_result). */
  validationSteps: ValidationStep[];
  workItem: string;
  /** Idempotency key → Squash `automated_test_reference` (≤50). */
  reference: string;
  file?: string;
  testId?: string;
}

const KIND_PREFIX: Record<CaseKind, string> = {
  positive: 'Positive',
  negative: 'Negative',
  edge: 'Edge',
};

/** Ensure the display name starts with the kind label so Squash and the UI stay readable. */
export function meaningfulCaseName(name: string, kind: CaseKind): string {
  const trimmed = name.trim() || 'Untitled case';
  const prefix = KIND_PREFIX[kind];
  if (new RegExp(`^${prefix}\\s*:`, 'i').test(trimmed)) return trimmed.slice(0, 255);
  if (/^(positive|negative|edge)\s*:/i.test(trimmed)) return trimmed.slice(0, 255);
  return `${prefix}: ${trimmed}`.slice(0, 255);
}

/** Default priority when the model omits it. */
export function defaultPriority(kind: CaseKind): CasePriority {
  if (kind === 'negative') return 'high';
  if (kind === 'edge') return 'low';
  return 'medium';
}

/**
 * Build Squash-facing validation steps from an optional list, a `// Steps:` comment
 * inside Playwright source, or a single fallback step from the case name + expected.
 */
export function resolveValidationSteps(input: {
  name: string;
  expected: string;
  steps?: string;
  validationSteps?: ValidationStep[];
}): ValidationStep[] {
  const explicit = (input.validationSteps ?? [])
    .map((s) => ({ action: s.action.trim(), expected: (s.expected ?? '').trim() }))
    .filter((s) => s.action);
  if (explicit.length > 0) return explicit.slice(0, 40);

  const fromComment = extractStepsComment(input.steps ?? '');
  if (fromComment.length > 0) {
    return fromComment.map((action, i, all) => ({
      action: action.slice(0, 4000),
      expected: i === all.length - 1 ? input.expected.slice(0, 4000) : '',
    }));
  }

  return [{
    action: `Verify: ${input.name}`.slice(0, 4000),
    expected: input.expected.slice(0, 4000),
  }];
}

function extractStepsComment(source: string): string[] {
  const match = /\/\/\s*Steps:\s*(.+)$/m.exec(source);
  if (!match?.[1]) return [];
  return match[1]
    .split(/(?<=[.!?])\s+/)
    .map((part) => part.trim())
    .filter((part) => part.length > 0)
    .slice(0, 40);
}

/** HTML description stored on the Squash test case (kind, priority, expected, automation ref). */
export function squashCaseDescription(input: {
  kind: CaseKind;
  priority: CasePriority;
  expected: string;
  workItem?: string;
  reference?: string;
  file?: string;
}): string {
  const esc = (value: string) => value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const lines = [
    `<p>Kind: ${esc(input.kind)} · Priority: ${esc(input.priority)}</p>`,
    input.workItem || input.reference
      ? `<p>${[input.workItem ? `Work item: ${esc(input.workItem)}` : '', input.reference ? `Reference: ${esc(input.reference)}` : ''].filter(Boolean).join(' · ')}</p>`
      : '',
    `<p>Expected: ${esc(input.expected.slice(0, 1500))}</p>`,
    input.file
      ? `<p>Automation: ${esc(input.file)} (playwright-test-generator)</p>`
      : '<p>Generated by playwright-test-generator.</p>',
  ].filter(Boolean);
  return lines.join('');
}

/** Payload for `tm.testcase.upsert` from a generated case row. */
export function toSquashUpsertInput(item: {
  name: string;
  kind?: CaseKind;
  priority?: CasePriority;
  steps: string;
  expected: string;
  validationSteps?: ValidationStep[];
  workItem?: string;
  reference: string;
  file?: string;
}): {
  reference: string;
  name: string;
  description: string;
  steps: ValidationStep[];
} {
  const kind: CaseKind = item.kind === 'negative' || item.kind === 'edge' || item.kind === 'positive' ? item.kind : 'positive';
  const priority: CasePriority = item.priority === 'high' || item.priority === 'medium' || item.priority === 'low'
    ? item.priority
    : defaultPriority(kind);
  const name = meaningfulCaseName(item.name, kind);
  const validationSteps = resolveValidationSteps({
    name,
    expected: item.expected,
    steps: item.steps,
    validationSteps: item.validationSteps,
  });
  return {
    reference: item.reference.slice(0, 50),
    name,
    description: squashCaseDescription({
      kind,
      priority,
      expected: item.expected,
      workItem: item.workItem,
      reference: item.reference,
      file: item.file,
    }),
    steps: validationSteps,
  };
}
